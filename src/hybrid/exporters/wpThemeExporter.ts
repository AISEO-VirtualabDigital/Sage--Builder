function renderNodeToHtml(node: any): string {
  if (!node) return ''
  if (node.type === 'text') {
    return `<div>${escapeHtml(String(node.props?.content || ''))}</div>`
  }
  if (node.type === 'image') {
    return `<img src="${escapeHtml(String(node.props?.src || ''))}" alt="${escapeHtml(String(node.props?.alt || ''))}" />`
  }
  if (node.type === 'button') {
    return `<a href="${escapeHtml(String(node.props?.href || '#'))}">${escapeHtml(String(node.props?.label || ''))}</a>`
  }
  if (node.type === 'video') {
    return `<video src="${escapeHtml(String(node.props?.src || ''))}" ${node.props?.controls ? 'controls' : ''}></video>`
  }
  if (node.type === 'divider') {
    return `<hr style="border: ${node.props?.thickness || '1px'} ${node.props?.style || 'solid'} ${node.props?.color || '#ccc'};" />`
  }
  if (node.type === 'spacer') {
    return `<div style="height: ${node.props?.height || '40px'};"></div>`
  }
  if (node.type === 'html') {
    return String(node.props?.code || '')
  }
  const children = (node.children || []).map(renderNodeToHtml).join('\n')
  const style = Object.entries(node.styles || {})
    .filter(([, v]) => v)
    .map(([k, v]) => `${camelToKebab(k)}: ${v}`)
    .join('; ')
  return `<div${style ? ` style="${style}"` : ''}>\n${children}\n</div>`
}

function getLanguageAttributes() {
  return '<?php language_attributes(); ?>'
}

function escapeHtml(str: string) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

function camelToKebab(str: string) {
  return str.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
}
