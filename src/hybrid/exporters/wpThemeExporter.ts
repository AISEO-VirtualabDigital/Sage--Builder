import type { Project } from '@/types'

export function exportWpTheme(project: Project) {
  const themeName = project.meta.title.replace(/[^a-z0-9]/gi, '-').toLowerCase() || 'sage-theme'
  const css = project.customCss || ''
  const js = project.customJs || ''
  const body = renderNodeToHtml(project.root)

  const files: Record<string, string> = {
    [`${themeName}/style.css`]: `/*
Theme Name: ${escapeHtml(project.meta.title || 'SAGE Theme')}
Author: ${escapeHtml(project.meta.author || 'SAGE')}
Description: ${escapeHtml(project.meta.description || 'Generated by SAGE Builder')}
Version: 1.0.0
*/
${css}`,
    [`${themeName}/functions.php`]: `<?php
add_action('wp_enqueue_scripts', function () {
  wp_enqueue_style('${themeName}-style', get_stylesheet_uri());
  wp_enqueue_script('${themeName}-script', get_template_directory_uri() . '/main.js', [], '1.0', true);
});
`,
    [`${themeName}/index.php`]: generateIndex(themeName, body, css, js),
    [`${themeName}/header.php`]: generateHeader(themeName),
    [`${themeName}/footer.php`]: generateFooter(),
    [`${themeName}/front-page.php`]: generateFrontPage(themeName, body, css, js),
    [`${themeName}/single.php`]: generateSingle(themeName),
    [`${themeName}/page.php`]: generatePage(themeName),
    [`${themeName}/archive.php`]: generateArchive(themeName),
    [`${themeName}/search.php`]: generateSearch(themeName),
    [`${themeName}/main.js`]: js,
  }

  return { name: themeName, files }
}

function generateIndex(_theme: string, body: string, css: string, js: string) {
  return `<!DOCTYPE html>
<html ${getLanguageAttributes()}>
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<title><?php wp_title('|', true, 'right'); ?></title>
<?php wp_head(); ?>
<style>${css}</style>
</head>
<body>
<header role="banner"><?php wp_body_open(); ?></header>
<div id="root">
${body}
</div>
<?php wp_footer(); ?>
<script>${js}</script>
</body>
</html>
`
}

